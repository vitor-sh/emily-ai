'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { JSDOM } = require('jsdom');
const app = fs.readFileSync('web/app.js', 'utf8');
const css = fs.readFileSync('web/estilo.css', 'utf8');
const dom = new JSDOM(`<body><style>${css}</style><div id="fluxo-in"></div></body>`, {runScripts:'outside-only', pretendToBeVisual:true});
const w = dom.window;
w.ICO = { cubo: '<path d="M1 1h2" />' };
w.svg = (icon, cls) => `<svg class="${cls}">${icon}</svg>`;
w.$ = (sel) => w.document.querySelector(sel);
w.ESTADO = { tela: 'chat', progresso: null, falasProcesso: [], emilyAberta: null, emilyBolhaDoTurno: null, ditoNoCartao: '', textoStream: '', acoesFimTarefa: [] };
w.rolarSePerto = () => {};
w._recolherAtividade = () => {};
w.textoVisivelSemTagsDeVoz = text => text;
w.deltaVisivelSemTagsDeVoz = text => text;
w.markdown = text => text;
w.novaMsg = (author, text) => { const el = w.document.createElement('article'); el.className = 'msg de-' + author; el.innerHTML = `<div class="msg-corpo">${text}</div>`; w.$('#fluxo-in').append(el); return el; };
w.fontesDaResposta = () => {};
w._desenharMarkdown = (el, text) => { el.textContent = text; };
w._textoLimpoDaBolha = () => w.ESTADO.ditoNoCartao;
w._marcarMensagemEstruturada = () => {};
// Seletor real do código, sem executar a inicialização inteira da aplicação.
w.eval(app.slice(app.indexOf('/* Espera de resposta:'), app.indexOf('/* ── Atividade das ferramentas')));
w.eval(app.slice(app.indexOf('function _renderBolha()'), app.indexOf('function emilyEscreve(')));
w.eval(app.slice(app.indexOf('function emilyDelta('), app.indexOf('/* Espera de resposta:')));
const wait = () => w.$('#digitando');
w.digitando(true);
assert.ok(wait(), 'indicador surge imediatamente após o envio');
assert.equal(wait().querySelector('.msg-autor'), null, 'não cria bolha da Emily');
assert.ok(wait().classList.contains('progresso'));
assert.ok(wait().classList.contains('indicador-espera'));
assert.ok(['Pensando', 'Calculando', 'Processando', 'Organizando as ideias'].includes(wait().textContent.trim()));
assert.equal(w.getComputedStyle(wait().querySelector('.progresso-rot')).fontSize, '14px');
assert.ok(css.includes('.progresso.trabalhando .progresso-rot'), 'usa o brilho das ferramentas');
assert.equal(w.$('.progresso-passos'), null, 'espera não falsifica eventos de ferramentas');
w.digitando(true);
assert.equal(w.document.querySelectorAll('#digitando').length, 1);
w.digitando(false);
assert.equal(wait(), null);
w.digitando(true);
w.emilyDelta('Resposta parcial');
assert.equal(wait(), null, 'primeiro token encerra espera');
assert.equal(w.$('.msg-corpo').textContent, 'Resposta parcial');
w.digitando(true);
w.emilyRespostaFinal('Resposta completa');
assert.equal(wait(), null, 'resposta final encerra espera');
assert.equal(w.$('.msg-corpo').textContent, 'Resposta completa');
w.ESTADO.ditoNoCartao = 'Resposta falada';
w.digitando(true);
w._renderBolha();
assert.equal(wait(), null, 'primeira fala visível encerra espera');
w.digitando(true);
w.digitando(false);
dom.window.close();
console.log('ok: espera animada, texto, limpeza, stream, fala e resposta final');
